import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { Claim, CompanyResearch, Idea } from "../research/types.js";
import { slugify } from "../research/research.js";

export interface IllustrativeMetric { label: string; value: string; note?: string }
export interface ProofOptions { candidateName?: string; roleTitle?: string; illustrativeMetrics?: IllustrativeMetric[] }

export const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const BADGE: Record<string, string> = { sourced: "SOURCED", inference: "INFERENCE", speculation: "SPECULATION" };

function srcLinks(c: { sources: { url: string; retrievedAt: string }[] }): string {
  if (!c.sources.length) return "";
  return `<span class="src">${c.sources.map((s) => `<a href="${esc(s.url)}" rel="noopener nofollow">${esc(new URL(s.url).host)}</a> <time>${esc(s.retrievedAt.slice(0, 10))}</time>`).join(", ")}</span>`;
}

// EVERY claim goes through this: no claim can render without a kind badge.
function claimLi(c: Claim): string {
  return `<li class="claim ${c.kind}"><span class="badge ${c.kind}">${BADGE[c.kind]}</span> ${esc(c.text)} ${srcLinks(c)}</li>`;
}
function section(title: string, claims: Claim[]): string {
  if (!claims.length) return "";
  return `<section><h2>${esc(title)}</h2><ul>${claims.map(claimLi).join("")}</ul></section>`;
}
function ideaCard(i: Idea, n: number): string {
  return `<article class="idea ${i.kind}"><h3>${n}. ${esc(i.title)}</h3><p><span class="badge ${i.kind}">${BADGE[i.kind]}</span> ${esc(i.rationale)} ${srcLinks(i)}</p></article>`;
}

export interface ProofRender { html: string; warnings: string[] }

export function renderProofHtml(r: CompanyResearch, opts: ProofOptions = {}): ProofRender {
  const warnings: string[] = [];
  const ideas = r.ideas.slice(0, 5);
  if (ideas.length < 3) warnings.push(`only ${ideas.length} idea(s) available (target 3-5); not padded`);
  if (r.source === "stub") warnings.push("research generated by stub (no LLM): content is thin; do not send externally");
  const metrics = opts.illustrativeMetrics?.length
    ? `<section class="illustrative"><h2>Illustrative scenario <span class="badge illustrative">ILLUSTRATIVE – NOT COMPANY DATA</span></h2><p>The figures below are hypothetical examples of how this analysis could be tracked. They are not measurements of ${esc(r.company)}.</p><div class="grid">${opts.illustrativeMetrics.map((m) => `<div class="metric"><b>${esc(m.value)}</b><span>${esc(m.label)}</span>${m.note ? `<small>${esc(m.note)}</small>` : ""}</div>`).join("")}</div></section>`
    : "";
  const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex,nofollow"><title>${esc(r.company)} – Proof of Work</title>
<style>
:root{--bg:#0f1115;--fg:#e8eaed;--mut:#9aa0a6;--card:#181b21;--bd:#2a2f38;--ok:#3ecf8e;--inf:#6ea8fe;--sp:#f5a524}
@media(prefers-color-scheme:light){:root{--bg:#fafafa;--fg:#1c1e21;--mut:#5f6368;--card:#fff;--bd:#e3e5e8}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--fg);font:16px/1.55 system-ui,sans-serif}
main{max-width:860px;margin:0 auto;padding:24px 16px 64px}h1{margin:.2em 0}h2{margin-top:2em;border-bottom:1px solid var(--bd);padding-bottom:.2em}
ul{padding-left:1.1em}li{margin:.5em 0}.src{display:block;font-size:.8em;color:var(--mut)}.src a{color:var(--inf)}
.badge{font-size:.68em;font-weight:700;letter-spacing:.04em;padding:.1em .5em;border-radius:99px;border:1px solid;white-space:nowrap}
.badge.sourced{color:var(--ok)}.badge.inference{color:var(--inf)}.badge.speculation,.badge.illustrative{color:var(--sp)}
.idea{background:var(--card);border:1px solid var(--bd);border-radius:12px;padding:12px 16px;margin:12px 0}.idea h3{margin:.2em 0}
.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:12px}.metric{background:var(--card);border:1px dashed var(--sp);border-radius:12px;padding:12px}
.metric b{display:block;font-size:1.6em}.metric span,.metric small{display:block;color:var(--mut)}
footer{margin-top:3em;padding-top:1em;border-top:1px solid var(--bd);color:var(--mut);font-size:.85em}
</style></head><body><main>
<p style="color:var(--mut)">Prepared${opts.candidateName ? ` by ${esc(opts.candidateName)}` : ""}${opts.roleTitle ? ` for the ${esc(opts.roleTitle)} role` : ""} · ${esc(r.generatedAt.slice(0, 10))}</p>
<h1>${esc(r.company)}: public-source analysis</h1>
<p>Legend: <span class="badge sourced">SOURCED</span> from a cited public page · <span class="badge inference">INFERENCE</span> reasoned from public info · <span class="badge speculation">SPECULATION</span> a hypothesis to test, not internal data.</p>
${section("Product", r.product)}${section("Strategy", r.strategy)}${section("Market", r.market)}${section("Recent news", r.news)}${section("Competitors", r.competitors)}${section("Hiring context", r.hiringContext)}${section("Business problems worth exploring", r.businessProblems)}
${ideas.length ? `<section><h2>Ideas</h2>${ideas.map((i, n) => ideaCard(i, n + 1)).join("")}</section>` : ""}
${metrics}
<footer>${esc(r.disclaimer)} This page is built only from publicly available information and contains no confidential or internal ${esc(r.company)} data.</footer>
</main></body></html>`;
  return { html, warnings };
}

export async function writeProofPage(r: CompanyResearch, opts: ProofOptions = {}, outRoot = "out/proof"): Promise<{ dir: string; file: string; warnings: string[] }> {
  const { html, warnings } = renderProofHtml(r, opts);
  const dir = join(outRoot, slugify(r.company));
  await mkdir(dir, { recursive: true });
  const file = join(dir, "index.html");
  await writeFile(file, html, "utf8");
  return { dir, file, warnings };
}
